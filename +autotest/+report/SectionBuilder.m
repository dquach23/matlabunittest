    %       .Defects        -- DefectRegister output
    %       .ProjectPrefix  -- char (e.g. 'RR')
    %
    %   Each section is a self-contained method that calls
    %   backend.addHeading / addParagraph / addTable on the supplied
    %   backend object, which then materialises to .docx (rptgen or
    %   ooxml).


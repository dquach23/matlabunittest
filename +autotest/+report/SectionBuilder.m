classdef SectionBuilder
    %SECTIONBUILDER  Phase 15 -- emit Sections 1..9 + Appendices A..D.
    %
    %   autotest.report.SectionBuilder.emit(backend, ctx)
    %
    %   CTX is a struct containing every input the section prose
    %   consumes:
    %       .Opts           -- options struct (DisplayName, etc.)
    %       .Data           -- ResultsParser output
    %       .Inventory      -- SourceInventory output
    %       .Defects        -- DefectRegister output
    %       .ProjectPrefix  -- char (e.g. 'RR')
    %
    %   Each section is a self-contained method that calls
    %   backend.addHeading / addParagraph / addTable on the supplied
    %   backend object, which then materialises to .docx (rptgen or
    %   ooxml).

    methods (Static)
        function cover(backend, opts)
            %COVER  v1.4 -- consolidated cover-page emitter (was CoverPage.m).
            %
            %   OPTS fields:
            %       DisplayName, DocVersion, ProjectOwner, DocDateIssued,
            %       TestCycle, DistReason, DistDate, DistController,
            %       Classification.
            %
            %   Visual delta vs the v1.3 CoverPage.emit:
            %     - Title is now Style.TitleFontSize (48pt) and bold.
            %     - Subtitle is Style.SubtitleFontSize (18pt) italic.
            %     - A 1pt accent-coloured rule sits between the metadata
            %       table and the Distribution Statement D box.
            %     - Classification line is added to the metadata table so
            %       the level appears on the cover even if a reader skims
            %       past the banner.
            arguments
                backend
                opts struct
            end
            distHeader = 'DISTRIBUTION STATEMENT D';
            distBody = sprintf( ...
                ['Distribution authorized to the Department of Defense and ' ...
                 'U.S. DoD contractors only; %s; %s.  Other requests for this ' ...
                 'document shall be referred to %s.'], ...
                opts.DistReason, opts.DistDate, opts.DistController);
            classification = autotest.report.SectionBuilder.optOrDefault( ...
                opts, 'Classification', 'UNCLASSIFIED');
            metadata = { ...
                'Test Cycle',        opts.TestCycle; ...
                'Date Issued',       opts.DocDateIssued; ...
                'Prepared For',      opts.ProjectOwner; ...
                'Prepared By',       'matlabunittest QA / autotest agent'; ...
                'Document Version',  opts.DocVersion; ...
                'Classification',    upper(strtrim(classification))};
            % v1.7: route the project prefix (e.g. "RR" for
            % removal_redaction_tool) into the cover-page monogram slot
            % so the cover gets a small charcoal emblem at top-left.
            monogram = '';
            if isfield(opts, 'ProjectPrefix') && ~isempty(opts.ProjectPrefix)
                monogram = char(opts.ProjectPrefix);
            end
            fields = struct( ...
                'Title',    opts.DisplayName, ...
                'Subtitle', 'System Test Report', ...
                'Metadata', {metadata}, ...
                'AccentRule', true, ...
                'Monogram',   monogram);
            backend.addCoverPage(fields, distHeader, distBody);
            % v1.7: bind the running page header (project name +
            % document version) on backends that expose setPageHeader
            % (OoxmlBackend).  HtmlBackend has its own banner mechanism;
            % no-op there.
            if ismethod(backend, 'setPageHeader')
                version = '';
                if isfield(opts, 'DocVersion') && ~isempty(opts.DocVersion)
                    version = ['v' char(opts.DocVersion)];
                end
                backend.setPageHeader(opts.DisplayName, version);
            end
        end

        function f = maybeDivider(backend)
            %MAYBEDIVIDER  v1.7 -- return a closure that emits a section divider when supported.
            %   Encapsulates the ismethod check so the emit() flow stays
            %   readable.  No-op on backends that pre-date addSectionDivider.
            if ismethod(backend, 'addSectionDivider')
                f = @() backend.addSectionDivider();
            else
                f = @() [];
            end
        end

        function v = optOrDefault(opts, name, default)
            if isstruct(opts) && isfield(opts, name) && ~isempty(opts.(name))
                v = char(opts.(name));
            else
                v = default;
            end
        end

        function emit(backend, ctx)
            % v1.7: insert lightweight 3-dot section dividers between
            % major sections.  Helps the eye chunk the document without
            % needing a page break (which is a heavier visual gesture).
            divider = autotest.report.SectionBuilder.maybeDivider(backend);
            autotest.report.SectionBuilder.executiveSummary(backend, ctx);
            divider();
            autotest.report.SectionBuilder.systemUnderTest(backend, ctx);
            divider();
            autotest.report.SectionBuilder.testScope(backend, ctx);
            divider();
            autotest.report.SectionBuilder.resultsSummary(backend, ctx);
            divider();
            autotest.report.SectionBuilder.detailedFindings(backend, ctx);
            divider();
            % v1.6: Failed Tests section -- one card per failure with
            % identifier, message, stack excerpt, and plain-English
            % explanation pattern-matched against known error families.
            autotest.report.SectionBuilder.failedTests(backend, ctx);
            divider();
            autotest.report.SectionBuilder.defectRegister(backend, ctx);
            divider();
            autotest.report.SectionBuilder.coverageRisk(backend, ctx);
            divider();
            autotest.report.SectionBuilder.recommendations(backend, ctx);
            divider();
            autotest.report.SectionBuilder.conclusion(backend, ctx);
            backend.addPageBreak();
            autotest.report.SectionBuilder.appendixA(backend, ctx);
            backend.addPageBreak();
            autotest.report.SectionBuilder.appendixB(backend, ctx);
            backend.addPageBreak();
            autotest.report.SectionBuilder.appendixC(backend, ctx);
            backend.addPageBreak();
            autotest.report.SectionBuilder.appendixD(backend, ctx);
            backend.addPageBreak();
            autotest.report.SectionBuilder.appendixE(backend, ctx);
        end

        % ====================================================== Section 1
        function executiveSummary(backend, ctx)
            d = ctx.Data;
            s = d.Summary;
            t = d.Totals;
            opts = ctx.Opts;
            pfx = ctx.ProjectPrefix;
            realCount = numel(d.KnownRealSignal);
            srcList = strjoin({ctx.Inventory.File}, ', ');
            backend.addHeading(1, '1. Executive Summary');

            backend.addParagraph(sprintf( ...
                ['This report documents the results of an automated system-level test ' ...
                 'pass against the %s.  Tests were generated by the matlabunittest ' ...
                 'autotest tool, which scans the project for MATLAB source artefacts ' ...
                 '(%d files in this pass: %s) and emits a matlab.unittest.TestCase ' ...
                 'scaffold per source.  The scaffold exercises every public function, ' ...
                 'method, property, and App Designer callback with a mix of smoke ' ...
                 'calls, per-argument edge cases, randomized property tests, and any ' ...
                 'documented help-text examples.  This verifies that the system can ' ...
                 'be loaded, instantiated, and exercised without raising unhandled ' ...
                 'errors against either realistic or degenerate inputs.'], ...
                opts.DisplayName, max(s.SourcesScanned, numel(ctx.Inventory)), srcList));

            backend.addParagraph(sprintf( ...
                ['The test pass executed %d generated tests in %.2f seconds.  %d ' ...
                 'passed, %d failed, and %d were classified Incomplete.  An ' ...
                 'additional %d user-stub tests are present in the _autotest/' ...
                 'user_tests tree as Incomplete-by-design placeholders awaiting ' ...
                 'hand-written assertions; they are not auto-runnable but appear in ' ...
                 'the totals as Incomplete.  Overall test result: %d passed, %d ' ...
                 'failed, %d Incomplete (%d generated + %d user-stub).'], ...
                s.GenTotal, s.DurationS, s.GenPassed, s.GenFailed, s.GenIncomplete, ...
                s.UserTotal, t.Passed, t.Failed, t.Incomplete, ...
                s.GenIncomplete, s.UserTotal));

            backend.addParagraph(sprintf( ...
                ['The single most important finding for this cycle is that %s ' ...
                 'produced %d unhandled failures across all %d generated invariant ' ...
                 'tests.  Every public surface that the autogenerator could exercise ' ...
                 'either succeeded against a synthesised or fixture-supplied input, ' ...
                 'or surfaced as a controlled Incomplete with a diagnostic explaining ' ...
                 'why a hand-written assertion is needed.'], ...
                opts.DisplayName, s.GenFailed, s.GenTotal));

            backend.addParagraph(sprintf( ...
                ['%d real-signal defects in the system under test were previously ' ...
                 'triaged and remain on the project''s accepted-debt list (see ' ...
                 'Section 6, Defect Register, and the project''s _autotest/' ...
                 'known_real_signal.txt manifest).  Defect IDs follow the %s-NNN ' ...
                 'convention.'], ...
                realCount, pfx));

            backend.addParagraph(sprintf( ...
                ['Owners of %s are encouraged to fill in the _autotest/user_tests/' ...
                 'u<Class>.m stubs with hand-written assertions to convert the %d ' ...
                 'Incomplete user-stub tests into meaningful Pass / Fail signal.  ' ...
                 'See Section 8 (Recommendations) for prioritised next steps.'], ...
                opts.DisplayName, s.UserTotal));
            % v1.6 callout strip -- four big-number summary boxes for the
            % core headline metrics.  Renders inline-block in HTML.
            % v1.7 (.docx): prefer addCalloutRow for horizontal layout
            % parity with HTML; fall back to per-callout addCalloutBox
            % on backends that lack the row method.
            if s.GenTotal > 0
                pctTxt = sprintf('%.1f%%', 100 * s.GenPassed / s.GenTotal);
            else
                pctTxt = 'n/a';
            end
            calloutItems = { ...
                num2str(s.GenTotal),  'tests generated'; ...
                num2str(s.GenPassed), 'passed'; ...
                num2str(s.GenFailed), 'failed'; ...
                pctTxt,               'generated pass rate'};
            if ismethod(backend, 'addCalloutRow')
                backend.addCalloutRow(calloutItems);
            elseif ismethod(backend, 'addCalloutBox')
                for i = 1:size(calloutItems,1)
                    backend.addCalloutBox(calloutItems{i,1}, calloutItems{i,2});
                end
            end
            % v1.7 KPI strip -- single full-width banded row below the
            % callouts.  Total / pass rate / failure count / run date,
            % packed glanceably with vertical dividers between values.
            if ismethod(backend, 'addKpiStrip')
                runDate = '';
                if isfield(s, 'Timestamp') && ~isempty(s.Timestamp)
                    runDate = char(s.Timestamp);
                end
                if isempty(runDate)
                    runDate = char(datetime('now','Format','yyyy-MM-dd'));
                else
                    % Compact display form: '20260511-101421' -> '2026-05-11'.
                    if length(runDate) >= 8
                        runDate = [runDate(1:4) '-' runDate(5:6) '-' runDate(7:8)];
                    end
                end
                % data.Totals has Passed/Failed/Incomplete/SuiteCount
                % but no aggregate Total; sum the three for the KPI.
                totalTests = t.Passed + t.Failed + t.Incomplete;
                kpiItems = { ...
                    num2str(totalTests),    'total tests'; ...
                    pctTxt,                 'pass rate'; ...
                    num2str(s.GenFailed),   'failures'; ...
                    runDate,                'run date'};
                backend.addKpiStrip(kpiItems);
            end
        end

        % ====================================================== Section 2
        function systemUnderTest(backend, ctx)
            inv = ctx.Inventory;
            opts = ctx.Opts;
            backend.addHeading(1, '2. System Under Test');
            backend.addParagraph(sprintf( ...
                ['%s is a MATLAB application.  The system comprises the source ' ...
                 'artefacts inventoried below; each summary line is quoted from ' ...
                 'the file''s classdef or function help text where present, and ' ...
                 'flagged as derived when no help text was available.  All ' ...
                 'sources are written in MATLAB R2025b syntax.'], opts.DisplayName));
            backend.addHeading(2, '2.1 Source Inventory');
            rows = cell(numel(inv), 3);
            for i = 1:numel(inv)
                rows{i,1} = inv(i).File;
                rows{i,2} = inv(i).Kind;
                rows{i,3} = inv(i).Summary;
            end
            backend.addTable({'File', 'Kind', 'Summary (from source)'}, ...
                rows, [3500, 2200, 3660]);
            backend.addHeading(2, '2.2 Test Targets');
            backend.addParagraph( ...
                ['Each source listed above produces one auto-generated test class ' ...
                 'under _autotest/generated/ (mirroring the source layout).  The ' ...
                 't<Source>.m naming convention is generated by matlabunittest.  ' ...
                 'An additional u<Source>.m hand-edit-friendly stub lives under ' ...
                 '_autotest/user_tests/ for the project owner to fill in with ' ...
                 'domain-specific assertions; those stubs are sticky across ' ...
                 'regenerations and never overwritten.']);
        end

        % ====================================================== Section 3
        function testScope(backend, ctx)
            opts = ctx.Opts;
            backend.addHeading(1, '3. Test Scope and Approach');
            backend.addParagraph( ...
                ['The test pass is scaffolding plus invariants, not "tests that ' ...
                 'know your spec."  The autogenerator can guarantee that every ' ...
                 'public function, method, and property is exercised; that obvious ' ...
                 'edge cases (empty, NaN, Inf, zero, negative, large, small) are ' ...
                 'applied to every numeric argument; and that no public surface ' ...
                 'throws an unhandled error against a randomized input within its ' ...
                 'declared type.  It cannot infer expected return values that the ' ...
                 'source did not document.']);
            backend.addHeading(2, '3.1 Test Categories Emitted');
            backend.addParagraph( ...
                ['The autogenerator emits the following test categories per source ' ...
                 'kind.  For .m functions: an existence test; a smoke test against ' ...
                 'scalar, vector, and matrix synthetic inputs; per-argument edge ' ...
                 'tests (empty, NaN, Inf, zero, neg, large, small); a randomized ' ...
                 'property test; and one test per Example block in the help text.  ' ...
                 'For .m classdefs: a constructor existence and smoke test; a ' ...
                 'get/set round-trip per public mutable property; and per-method ' ...
                 'smoke + edge + randomized + doc-example tests with the instance ' ...
                 'vs. Static distinction respected.  For .mlapp App Designer files: ' ...
                 'launch and teardown, a verification that a matlab.ui.Figure ' ...
                 'handle is present, and one test per declared callback invoked ' ...
                 'with a synthetic event struct.']);
            backend.addHeading(2, '3.2 Fixture Layer');
            backend.addParagraph(sprintf( ...
                ['Where the project supplies real fixtures (e.g., a sample .xlsx ' ...
                 'workbook), the autogenerator wires them into the test inputs.  ' ...
                 'Helper-string arguments are name-driven: arguments named cellRef ' ...
                 'receive ''A1'', tableName receives ''Table1'', filePath receives ' ...
                 'tempname() or the primary Excel path, and so on.  Phase 14 added ' ...
                 'unzipped-Excel staging fixtures and typed table / cell inputs.  ' ...
                 'Phase 15 adds three additional generic mechanisms (live-state-' ...
                 'aware smoke inputs; full-fixture DOM smokes; typed data / value ' ...
                 '/ payload inputs) -- see Appendix C for the methodology note.']));
            backend.addHeading(2, '3.3 Disposition Tiers');
            backend.addParagraph( ...
                ['Each generated test reports as Pass, Fail, or Incomplete.  Pass ' ...
                 'means the test ran to completion against the synthesised input ' ...
                 'with no unhandled exception.  Fail means an unhandled exception ' ...
                 'escaped or a verification assertion produced a mismatch.  ' ...
                 'Incomplete is a deliberate signal that the test could not be ' ...
                 'meaningfully completed -- common reasons include opaque-typed ' ...
                 'inputs that the autogenerator cannot synthesize (containers.Map, ' ...
                 'dictionary, DOM nodes), entries on the project''s ' ...
                 'known_real_signal.txt manifest (a known real bug the user has ' ...
                 'chosen to triage rather than fix), and user-stub tests awaiting ' ...
                 'hand-written assertions.']);
        end

        % ====================================================== Section 4
        function resultsSummary(backend, ctx)
            d = ctx.Data;
            s = d.Summary;
            t = d.Totals;
            backend.addHeading(1, '4. Test Results Summary');
            if s.GenTotal > 0
                passPct = sprintf('%.1f%%', s.GenPassed / s.GenTotal * 100);
            else
                passPct = 'n/a';
            end
            backend.addParagraph(sprintf( ...
                ['The headline metrics for the test cycle are shown in the table ' ...
                 'below.  All %d generated tests executed; %d (%s of generated) ' ...
                 'passed, %d failed, %d were Incomplete with diagnostic context.  ' ...
                 'User-stub tests are Incomplete by design and are excluded from ' ...
                 'the percentage calculation.'], ...
                s.GenTotal, s.GenPassed, passPct, s.GenFailed, s.GenIncomplete));
            backend.addHeading(2, '4.1 Headline Metrics');
            rows = { ...
                'Tests defined',                num2str(s.GenTotal),     num2str(s.UserTotal), num2str(s.Total); ...
                'Passed',                       num2str(s.GenPassed),    '0',                  num2str(t.Passed); ...
                'Failed',                       num2str(s.GenFailed),    '0',                  num2str(t.Failed); ...
                'Incomplete',                   num2str(s.GenIncomplete),num2str(s.UserTotal), num2str(t.Incomplete); ...
                'Pass percentage (of generated)', passPct,             'n/a',                passPct; ...
                'Wall-clock duration',          sprintf('%.2f s', s.DurationS), '0 s (not auto-run)', sprintf('%.2f s', s.DurationS) };
            backend.addTable({'Metric', 'Generated', 'User-stub', 'Total'}, ...
                rows, [3500, 2000, 1900, 1960]);
            % v1.4 (B.1): pie chart of pass / fail / incomplete.  Rendered
            % to a tempfile via figure -> pie -> print('-dpng','-r150')
            % and embedded inline.  Colours follow the locked palette:
            % muted gold for passed, deep red for failed, slate for
            % incomplete.  Best-effort -- any failure here just skips
            % the chart and continues with the existing tabular data.
            try
                if ismethod(backend, 'addSvgChart')
                    svg = autotest.report.backends.HtmlBackend.pieChartSvg( ...
                        s.GenPassed, s.GenFailed, s.GenIncomplete);
                    if ~isempty(svg)
                        backend.addSvgChart(svg);
                    end
                else
                    pngPie = autotest.report.SectionBuilder.renderPieChart( ...
                        s.GenPassed, s.GenFailed, s.GenIncomplete);
                    if ~isempty(pngPie)
                        % v1.6: fill the available content width and
                        % preserve the 1200x700 source aspect ratio
                        % (9360 DXA wide => 5460 DXA tall).
                        backend.addImage(pngPie, 9360, 5460);
                    end
                end
            catch ME
                warning('autotest:report:pie', 'Pie chart skipped: %s', ME.message);
            end
            backend.addHeading(2, '4.2 Per-Source Breakdown');
            backend.addParagraph( ...
                ['The pass-rate per source file is shown below.  Failures remain ' ...
                 'at zero across every source; the Incomplete column reflects the ' ...
                 'combination of opaque-typed inputs, project bugs on the ' ...
                 'accepted-debt list, and synthetic-input mismatches that the ' ...
                 'autogenerator could not work around without hand-written domain ' ...
                 'knowledge.  Section 5 walks each source in detail.']);
            perSrcRows = cell(numel(d.PerSource), 4);
            for i = 1:numel(d.PerSource)
                p = d.PerSource(i);
                perSrcRows{i,1} = p.File;
                perSrcRows{i,2} = num2str(p.Passed);
                perSrcRows{i,3} = num2str(p.Failed);
                perSrcRows{i,4} = num2str(p.Incomplete);
            end
            if isempty(perSrcRows)
                perSrcRows = {'(no per-source data parsed from summary.txt)', '', '', ''};
            end
            backend.addTable({'Source file', 'Passed', 'Failed', 'Incomplete'}, ...
                perSrcRows, [3700, 1900, 1900, 1860]);
        end

        % ====================================================== Section 5
        function detailedFindings(backend, ctx)
            d = ctx.Data;
            backend.addHeading(1, '5. Detailed Findings by Source File');
            backend.addParagraph( ...
                ['This section walks each source file in the system, summarising ' ...
                 'the test outcomes against that source and highlighting any ' ...
                 'defect IDs that originated in it.  Defect IDs cross-reference ' ...
                 'Section 6 (Defect Register).']);
            % v1.4 (B.2): horizontal bar chart of pass rate per source
            % file.  Reuses the OoxmlBackend image-embed path added in
            % B.1; rendered at 150 DPI and embedded inline above the
            % per-source narrative.  Best-effort.
            try
                if ismethod(backend, 'addSvgChart')
                    svg = autotest.report.backends.HtmlBackend.barChartSvg(d.PerSource);
                    if ~isempty(svg)
                        backend.addSvgChart(svg);
                    end
                else
                    pngBar = autotest.report.SectionBuilder.renderBarChart(d.PerSource);
                    if ~isempty(pngBar)
                        n = numel(d.PerSource);
                        % v1.6: fill content width and scale height
                        % proportional to the 1400x(48n+160) source.
                        % heightDxa = 9360 * srcH / 1400.
                        srcH = max(420, 48 * n + 160);
                        heightDxa = round(9360 * srcH / 1400);
                        backend.addImage(pngBar, 9360, heightDxa);
                    end
                end
            catch ME
                warning('autotest:report:bar', 'Bar chart skipped: %s', ME.message);
            end
            for i = 1:numel(d.PerSource)
                p = d.PerSource(i);
                backend.addHeading(2, sprintf('5.%d  %s', i, p.File));
                backend.addParagraph(sprintf( ...
                    'Result: %d of %d tests passed; %d failed; %d Incomplete.', ...
                    p.Passed, p.Total, p.Failed, p.Incomplete));
                backend.addParagraph(autotest.report.SectionBuilder.findingForSource( ...
                    p.File, p, d, ctx));
            end
        end

        function txt = findingForSource(file, p, d, ctx) %#ok<INUSL>
            % Generic per-source narrative.  Reuses the totals from the
            % JUnit results to call out specific cluster reasons (state,
            % opaque-input, real-signal) without hardcoding class names.
            cls = autotest.report.SectionBuilder.classNameForFile(file);
            tests = d.Tests(strcmp({d.Tests.Class}, cls));
            failed = sum(strcmp({tests.Status}, 'failed'));
            inc    = sum(strcmp({tests.Status}, 'incomplete'));
            pass   = sum(strcmp({tests.Status}, 'passed'));
            if isempty(tests)
                txt = sprintf( ...
                    ['No matching test class was found in results.xml for ' ...
                     '%s; the per-source counts above are derived from ' ...
                     'summary.txt only.  This is normal for sources whose test ' ...
                     'class produced an empty suite.'], file);
                return;
            end
            % Categorise Incomplete reasons.
            opaque   = 0; statefulCount = 0; realSig = 0; userStub = 0;
            for k = 1:numel(tests)
                m = lower(char(tests(k).Message));
                if strcmp(tests(k).Status, 'incomplete')
                    if contains(m, 'opaque-typed'),                     opaque = opaque + 1;
                    elseif contains(m, 'stateful class'),               statefulCount = statefulCount + 1;
                    elseif contains(m, 'known-real-signal') || contains(m, 'project bug'), realSig = realSig + 1;
                    else,                                                userStub = userStub + 1;
                    end
                end
            end
            txt = sprintf( ...
                ['%d of %d tests passed; %d failed; %d Incomplete.  ' ...
                 'Of the %d Incomplete: %d opaque-typed-input cascade, %d ' ...
                 'stateful-input mismatch on a populated instance, %d on the ' ...
                 'project''s known-real-signal accepted-debt list, %d ' ...
                 'miscellaneous (autogen-side scaffolding limitations).'], ...
                pass, pass + failed + inc, failed, inc, ...
                inc, opaque, statefulCount, realSig, userStub);
        end

        function cls = classNameForFile(file)
            [~, base, ~] = fileparts(file);
            cls = ['t' base];
        end

        % ====================================================== Section 5.5
        function failedTests(backend, ctx)
            %FAILEDTESTS  v1.6 -- one card per failed test with explanation.
            %
            %   For each test whose Status is 'failed' or 'error', emit a
            %   compact card listing: test identifier, the MATLAB error
            %   identifier extracted from the diagnostic, the headline
            %   message, a 3-frame stack excerpt, and a plain-English
            %   explanation pattern-matched against the
            %   FailureExplainer.knownPatterns table.  Unrecognised
            %   errors render with a "Cause not classified -- investigate
            %   manually" hint rather than fabricating a confident-but-
            %   wrong explanation.  This section sits between Section 5
            %   (per-source narrative) and the existing Section 6
            %   (Defect Register) so the operator scans Pass/Fail
            %   metrics, drills into per-source rows, then sees every
            %   failure inline before the formal defect catalogue.
            d = ctx.Data;
            failed = d.Tests(strcmp({d.Tests.Status}, 'failed') | ...
                             strcmp({d.Tests.Status}, 'error'));
            backend.addHeading(1, sprintf('Failed Tests (%d)', numel(failed)));
            if isempty(failed)
                backend.addParagraph( ...
                    ['No tests failed in this cycle.  This section is ' ...
                     'reserved for per-failure diagnostics + plain-' ...
                     'English explanations; it stays empty when the ' ...
                     'cycle is clean.']);
                return;
            end
            backend.addParagraph(sprintf( ...
                ['This section enumerates every test that returned a ' ...
                 'Failed or Error disposition in this cycle (%d ' ...
                 'total).  Each card lists the test identifier, the ' ...
                 'MATLAB error identifier and headline message, a ' ...
                 'short stack excerpt, and -- where the autogen ' ...
                 'recognises the error family -- a plain-English ' ...
                 'explanation and likely fix.  Unrecognised errors ' ...
                 'still appear here with their identifier and message ' ...
                 'verbatim; consult Appendix B for the full diagnostic.'], ...
                numel(failed)));
            for i = 1:numel(failed)
                t = failed(i);
                [expl, ident, msg, stack] = ...
                    autotest.report.FailureExplainer.explain(t);
                info = struct( ...
                    'Class',       t.Class, ...
                    'Method',      t.Method, ...
                    'Identifier',  ident, ...
                    'Message',     msg, ...
                    'Stack',       {stack}, ...
                    'Explanation', expl);
                if ismethod(backend, 'addFailureCard')
                    backend.addFailureCard(info);
                else
                    % Fallback for backends that predate the failure-card
                    % method: render as a normal heading + paragraph.
                    backend.addHeading(3, sprintf('%s.%s', t.Class, t.Method));

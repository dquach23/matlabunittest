        function out = diagnosticSamples(defect, data)
            % Phase 16 (Part B item 6): cap raised from 3 to 6 samples
            % per defect.  When the defect has a populated AffectedMethods
            % list (set by the stateful-cluster path), filter samples to
            % methods that appear in that list -- ensures the diagnostics
            % shown for cluster RR-NNN actually belong to that cluster
            % and not a sibling cluster on the same class.  Every DEFECTID
            % called out in Section 6 gets at least one sample emitted in
            % Appendix B (even if the per-cluster filter returns zero,
            % the category fallback finds at least one matching test).
            out = struct('Class',{},'Method',{},'Message',{});
            cat = defect.Category;
            cap = 6;
            % Pass 1: cluster-precise (when defect carries an
            % AffectedMethods list, prefer those tests).
            wantedMethods = {};
            if isfield(defect, 'AffectedMethods') ...
                    && ~isempty(defect.AffectedMethods)
                wantedMethods = defect.AffectedMethods;
            end
            count = 0;
            if ~isempty(wantedMethods)
                for i = 1:numel(data.Tests)
                    if count >= cap, break; end
                    t = data.Tests(i);
                    if strcmp(t.Status, 'passed'), continue; end
                    if ~any(strcmp(t.Method, wantedMethods)), continue; end
                    out(end+1) = struct('Class', t.Class, ...
                        'Method', t.Method, ...
                        'Message', char(t.Message)); %#ok<AGROW>
                    count = count + 1;
                end
            end
            if count >= cap, return; end
            % Pass 2: category match.
            for i = 1:numel(data.Tests)
                if count >= cap, break; end
                t = data.Tests(i);
                if strcmp(t.Status, 'passed'), continue; end
                if any(strcmp(t.Method, {out.Method})) ...
                        && any(strcmp(t.Class, {out.Class}))
                    continue;
                end
                m = lower(char(t.Message));
                hit = false;
                switch cat
                    case 'real-signal'
                        if contains(m, 'known-real-signal') || contains(m, 'project bug')
                            hit = true;
                        end
                    case 'stateful-input-mismatch'
                        if contains(m, 'stateful class')
                            hit = true;
                        end
                    case 'opaque-typed-input'
                        if contains(m, 'opaque-typed')
                            hit = true;
                        end
                    case 'user-stub'
                        if contains(m, 'todo') || contains(m, 'fill in user') ...
                                || contains(m, 'stub')
                            hit = true;
                        end
                end
                if hit
                    out(end+1) = struct('Class', t.Class, 'Method', t.Method, ...
                        'Message', char(t.Message)); %#ok<AGROW>
                    count = count + 1;
                end
            end
            % Belt-and-braces: if STILL empty (e.g. an unusual category
            % with no matching test), pull the first non-passing test
            % so Appendix B always has at least one entry per defect.
            if count == 0
                for i = 1:numel(data.Tests)
                    t = data.Tests(i);
                    if strcmp(t.Status, 'passed'), continue; end
                    out(end+1) = struct('Class', t.Class, 'Method', t.Method, ...
                        'Message', char(t.Message)); %#ok<AGROW>
                    break;
                end
            end
        end


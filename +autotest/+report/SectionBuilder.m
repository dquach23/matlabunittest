        function txt = findingForSource(file, p, d, ctx) %#ok<INUSL>
            % Generic per-source narrative.  Reuses the totals from the
            % JUnit results to call out specific cluster reasons (state,
            % opaque-input, real-signal) without hardcoding class names.
            cls = autotest.report.SectionBuilder.classNameForFile(file);
            tests = d.Tests(strcmp({d.Tests.Class}, cls));
            failed = sum(strcmp({tests.Status}, 'failed'));
            inc    = sum(strcmp({tests.Status}, 'incomplete'));
            pass   = sum(strcmp({tests.Status}, 'passed'));
            if isempty(tests)
                txt = sprintf( ...
                    ['No matching test class was found in results.xml for ' ...
                     '%s; the per-source counts above are derived from ' ...
                     'summary.txt only.  This is normal for sources whose test ' ...
                     'class produced an empty suite.'], file);
                return;
            end
            % Categorise Incomplete reasons.
            opaque   = 0; statefulCount = 0; realSig = 0; userStub = 0;
            for k = 1:numel(tests)
                m = lower(char(tests(k).Message));
                if strcmp(tests(k).Status, 'incomplete')
                    if contains(m, 'opaque-typed'),                     opaque = opaque + 1;
                    elseif contains(m, 'stateful class'),               statefulCount = statefulCount + 1;
                    elseif contains(m, 'known-real-signal') || contains(m, 'project bug'), realSig = realSig + 1;
                    else,                                                userStub = userStub + 1;
                    end
                end
            end
            txt = sprintf( ...
                ['%d of %d tests passed; %d failed; %d Incomplete.  ' ...
                 'Of the %d Incomplete: %d opaque-typed-input cascade, %d ' ...
                 'stateful-input mismatch on a populated instance, %d on the ' ...
                 'project''s known-real-signal accepted-debt list, %d ' ...
                 'miscellaneous (autogen-side scaffolding limitations).'], ...
                pass, pass + failed + inc, failed, inc, ...
                inc, opaque, statefulCount, realSig, userStub);
        end

        function cls = classNameForFile(file)
            [~, base, ~] = fileparts(file);
            cls = ['t' base];
        end


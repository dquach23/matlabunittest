            backend.addPageBreak();
            autotest.report.SectionBuilder.appendixB(backend, ctx);
            backend.addPageBreak();
            autotest.report.SectionBuilder.appendixC(backend, ctx);
            backend.addPageBreak();
            autotest.report.SectionBuilder.appendixD(backend, ctx);
            backend.addPageBreak();

        function v = fieldOrDefault(s, name, default)
            if isstruct(s) && isfield(s, name) && ~isempty(s.(name))
                val = s.(name);
                if ischar(val), v = val;
                elseif isstring(val), v = char(val);
                elseif isnumeric(val) && isscalar(val), v = num2str(val);
                else, v = default;
                end
            else
                v = default;
            end
        end


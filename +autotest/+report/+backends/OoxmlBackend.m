        function s = codeLineXml(line)
            %CODELINEXML  v1.4 (B.4) -- one monospace, light-grey-filled line.
            %   Each diagnostic line gets its own <w:p> sharing the same
            %   shading + font so consecutive lines render as a contiguous
            %   monospace block.  Tight before/after spacing keeps the
            %   block compact.
            sz   = autotest.report.Style.CodeFontSize;
            font = autotest.report.Style.CodeFontName;
            fill = autotest.report.Style.CodeFill;
            txt  = autotest.report.backends.OoxmlBackend.xmlEsc(line);
            if isempty(line), txt = ' '; end  % preserve blank line height
            s = [ ...
                '<w:p>' ...
                '<w:pPr>' ...
                '<w:shd w:val="clear" w:color="auto" w:fill="' fill '"/>' ...
                '<w:spacing w:before="0" w:after="0" w:line="240" w:lineRule="auto"/>' ...
                '<w:ind w:left="120" w:right="120"/>' ...
                '</w:pPr>' ...
                '<w:r>' ...
                '<w:rPr>' ...
                '<w:rFonts w:ascii="' font '" w:hAnsi="' font '" w:cs="' font '"/>' ...
                sprintf('<w:sz w:val="%d"/><w:szCs w:val="%d"/>', sz, sz) ...
                '</w:rPr>' ...
                '<w:t xml:space="preserve">' txt '</w:t>' ...
                '</w:r>' ...
                '</w:p>'];
        end

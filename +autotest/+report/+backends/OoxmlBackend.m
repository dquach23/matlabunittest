    methods (Static, Access = private)
        function out = xmlEsc(text)
            % Escape &, <, >, ", '
            t = char(text);
            t = strrep(t, '&', '&amp;');
            t = strrep(t, '<', '&lt;');
            t = strrep(t, '>', '&gt;');
            t = strrep(t, '"', '&quot;');
            t = strrep(t, '''', '&apos;');
            out = t;
        end

        function s = cellXml(text, widthDxa, bold, shadeColor)
            tcPr = sprintf('<w:tcW w:w="%d" w:type="dxa"/>', widthDxa);
            if ~isempty(shadeColor)
                tcPr = [tcPr sprintf('<w:shd w:val="clear" w:color="auto" w:fill="%s"/>', shadeColor)];
            end
            tcPr = [tcPr ...
                '<w:tcMar>' ...
                '<w:top w:w="80" w:type="dxa"/>' ...
                '<w:left w:w="120" w:type="dxa"/>' ...
                '<w:bottom w:w="80" w:type="dxa"/>' ...
                '<w:right w:w="120" w:type="dxa"/>' ...
                '</w:tcMar>'];
            rpr = '';
            if bold, rpr = '<w:rPr><w:b/></w:rPr>'; end
            txtEsc = autotest.report.backends.OoxmlBackend.xmlEsc(text);
            s = ['<w:tc><w:tcPr>' tcPr '</w:tcPr>' ...
                 '<w:p><w:r>' rpr '<w:t xml:space="preserve">' txtEsc '</w:t></w:r></w:p>' ...
                 '</w:tc>'];
        end


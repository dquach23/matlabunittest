    methods (Static, Access = private)
        function out = xmlEsc(text)
            % Escape &, <, >, ", '
            t = char(text);
            t = strrep(t, '&', '&amp;');
            t = strrep(t, '<', '&lt;');
            t = strrep(t, '>', '&gt;');
            t = strrep(t, '"', '&quot;');
            t = strrep(t, '''', '&apos;');
            out = t;
        end

        function s = cellXml(text, widthDxa, bold, shadeColor)
            % v1.6: detect [STATUS:<name>] sentinel and render the cell
            % as a status badge -- coloured pill text on a fill matching
            % the v1.6 badge palette.  Falls through to plain rendering
            % when the sentinel is absent.
            txtChar = char(text);
            statusTok = regexp(txtChar, '^\[STATUS:([A-Za-z]+)\]$', ...
                'tokens', 'once');
            if ~isempty(statusTok)
                [fillHex, textHex, label] = ...
                    autotest.report.Style.statusBadge(statusTok{1});
                tcPr = sprintf('<w:tcW w:w="%d" w:type="dxa"/>', widthDxa);
                tcPr = [tcPr sprintf( ...
                    '<w:shd w:val="clear" w:color="auto" w:fill="%s"/>', ...
                    fillHex)];
                tcPr = [tcPr ...
                    '<w:tcMar>' ...
                    '<w:top w:w="60" w:type="dxa"/>' ...
                    '<w:left w:w="100" w:type="dxa"/>' ...
                    '<w:bottom w:w="60" w:type="dxa"/>' ...
                    '<w:right w:w="100" w:type="dxa"/>' ...
                    '</w:tcMar>'];
                lbl = autotest.report.backends.OoxmlBackend.xmlEsc(upper(label));
                s = ['<w:tc><w:tcPr>' tcPr '</w:tcPr>' ...
                     '<w:p><w:pPr><w:jc w:val="center"/></w:pPr><w:r>' ...
                     '<w:rPr><w:b/>' ...
                     '<w:rFonts w:ascii="Calibri" w:hAnsi="Calibri"/>' ...
                     '<w:color w:val="' textHex '"/>' ...
                     '<w:sz w:val="18"/><w:szCs w:val="18"/>' ...
                     '</w:rPr><w:t xml:space="preserve">' lbl ...
                     '</w:t></w:r></w:p></w:tc>'];
                return;
            end
            tcPr = sprintf('<w:tcW w:w="%d" w:type="dxa"/>', widthDxa);
            if ~isempty(shadeColor)
                tcPr = [tcPr sprintf('<w:shd w:val="clear" w:color="auto" w:fill="%s"/>', shadeColor)];
            end
            tcPr = [tcPr ...
                '<w:tcMar>' ...
                '<w:top w:w="80" w:type="dxa"/>' ...
                '<w:left w:w="120" w:type="dxa"/>' ...
                '<w:bottom w:w="80" w:type="dxa"/>' ...
                '<w:right w:w="120" w:type="dxa"/>' ...
                '</w:tcMar>'];
            rpr = '';
            if bold, rpr = '<w:rPr><w:b/></w:rPr>'; end
            txtEsc = autotest.report.backends.OoxmlBackend.xmlEsc(text);
            s = ['<w:tc><w:tcPr>' tcPr '</w:tcPr>' ...
                 '<w:p><w:r>' rpr '<w:t xml:space="preserve">' txtEsc '</w:t></w:r></w:p>' ...
                 '</w:tc>'];
        end


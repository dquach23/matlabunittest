        function files = listAllFiles(stageDir)
            files = {};
            list = dir(fullfile(stageDir, '**', '*'));
            for i = 1:numel(list)
                d = list(i);
                if d.isdir, continue; end
                full = fullfile(d.folder, d.name);
                rel = strrep(full, [stageDir filesep], '');
                files{end+1} = rel; %#ok<AGROW>
            end
        end

        function s = classificationBannerXml(level)
            %CLASSIFICATIONBANNERXML  v1.4 (CAPCO colour) + v1.6 (DoDM plain).
            %   Per DoDM 5200.01 V2, UNCLASSIFIED documents use a plain
            %   centred-text banner -- no coloured background block.
            %   Higher classifications keep the v1.4 CAPCO colour map
            %   (UNCLASSIFIED green is no longer applied, per the spec).
            sz   = autotest.report.Style.BannerFontSize;
            txt  = autotest.report.backends.OoxmlBackend.xmlEsc(upper(strtrim(level)));
            if autotest.report.Style.isUnclassified(level)
                % Plain text, charcoal, centred; no shading, no colour box.
                s = [ ...
                    '<w:p>' ...
                    '<w:pPr>' ...
                    '<w:jc w:val="center"/>' ...
                    '<w:spacing w:before="0" w:after="0"/>' ...
                    '<w:pBdr>' ...
                    '<w:top w:val="single" w:sz="4" w:color="D1D5DB"/>' ...
                    '<w:bottom w:val="single" w:sz="4" w:color="D1D5DB"/>' ...
                    '</w:pBdr>' ...
                    '</w:pPr>' ...
                    '<w:r>' ...
                    '<w:rPr>' ...
                    '<w:rFonts w:ascii="Calibri" w:hAnsi="Calibri"/>' ...
                    '<w:b/>' ...
                    '<w:color w:val="' autotest.report.Style.PrimaryText '"/>' ...
                    sprintf('<w:sz w:val="%d"/><w:szCs w:val="%d"/>', sz, sz) ...
                    '</w:rPr>' ...
                    '<w:t xml:space="preserve">' txt '</w:t>' ...
                    '</w:r>' ...
                    '</w:p>'];
            else
                fill = autotest.report.Style.classificationFill(level);
                s = [ ...
                    '<w:p>' ...
                    '<w:pPr>' ...
                    '<w:shd w:val="clear" w:color="auto" w:fill="' fill '"/>' ...
                    '<w:jc w:val="center"/>' ...
                    '<w:spacing w:before="0" w:after="0"/>' ...

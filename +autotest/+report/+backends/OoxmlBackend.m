        function files = listAllFiles(stageDir)
            files = {};
            list = dir(fullfile(stageDir, '**', '*'));
            for i = 1:numel(list)
                d = list(i);
                if d.isdir, continue; end
                full = fullfile(d.folder, d.name);
                rel = strrep(full, [stageDir filesep], '');
                files{end+1} = rel; %#ok<AGROW>
            end
        end

                    '<w:r>' ...
                    '<w:rPr>' ...
                    '<w:rFonts w:ascii="Calibri" w:hAnsi="Calibri"/>' ...
                    '<w:b/>' ...
                    '<w:color w:val="FFFFFF"/>' ...
                    sprintf('<w:sz w:val="%d"/><w:szCs w:val="%d"/>', sz, sz) ...
                    '</w:rPr>' ...
                    '<w:t xml:space="preserve">' txt '</w:t>' ...
                    '</w:r>' ...
                    '</w:p>'];
            end
        end

        function s = drawingParagraphXml(relId, idNum, widthEmu, heightEmu)

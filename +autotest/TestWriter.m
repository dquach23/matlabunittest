        function s = escapeString(text)
            s = strrep(text, '\', '\\');
            s = strrep(s, '''', '''''');
            s = strrep(s, sprintf('\n'), '\\n');
            s = strrep(s, sprintf('\r'), '\\r');
            s = strrep(s, '%', '%%');
        end

        function s = escapeCharLiteral(text)
            s = strrep(text, '''', '''''');
        end

        function out = iif(cond, a, b)
            if cond
                out = a;
            else
                out = b;
            end
        end

        function expr = sampleForType(prop)
            t = lower(strtrim(char(prop.Type)));
            if isempty(t)
                expr = '1';
                return;
            end
            t = regexprep(t, '\([^)]*\)', '');
            t = strtrim(t);
            parts = strsplit(t);
            base = '';
            if ~isempty(parts), base = parts{1}; end
            switch base
                case {'double','single','numeric',''}
                    expr = '1';
                case {'int8','int16','int32','int64', ...
                      'uint8','uint16','uint32','uint64'}
                    expr = sprintf('%s(1)', base);
                case 'logical'
                    expr = 'true';
                case 'char'
                    expr = '''x''';
                case 'string'
                    expr = '"x"';
                case 'cell'
                    expr = '{1}';
                case 'struct'
                    expr = 'struct(''f'', 1)';
                case 'datetime'
                    expr = 'datetime(2024,1,1)';
                case 'duration'
                    expr = 'seconds(1)';
                case 'categorical'
                    expr = 'categorical("a")';
                case 'function_handle'
                    expr = '@(x) x';
                otherwise
                    expr = '';
            end
        end
